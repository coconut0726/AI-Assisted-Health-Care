// Service worker for the installed web app.
// Pages: network first, so a new build shows up as soon as the phone is online; the cached copy is used offline.
// Other same-origin files (JS bundle, fonts, icons): cache first, since their names change with each build.
// API calls to the care-plan server are never cached.
const CACHE = 'ahc-web-v2';

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;

  if (req.mode === 'navigate') {
    // Single-page app: every page is index.html. Static hosts answer 404 for /nurse/james etc., so load '/' instead.
    event.respondWith(
      fetch(req)
        .then((res) => (res.ok ? res : fetch('/')))
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put('/', copy));
          }
          return res;
        })
        .catch(() => caches.match('/')),
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
